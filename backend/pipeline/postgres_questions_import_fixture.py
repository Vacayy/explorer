"""Import a scoped SQLite question snapshot into an empty disposable PG fixture."""
from psycopg import sql

from pipeline.postgres_graph_fixture import _guard

TABLES = ('questions', 'sub_questions', 'question_reports', 'proxy_registry',
          'proxy_observations', 'proxy_scans', 'proxy_boards', 'proxy_board_items', 'scenarios')


def import_questions(source, target):
    """Import atomically; never replace existing tables or run queued work.

    External document, narrative and transcript references are retained as IDs,
    and must be checked against the destination snapshot separately.
    """
    _guard(target)
    if not source.in_transaction or source.execute('PRAGMA query_only').fetchone()[0] != 1:
        raise ValueError('A query-only SQLite read transaction is required')
    types = {'INTEGER': sql.SQL('BIGINT'), 'REAL': sql.SQL('DOUBLE PRECISION'), 'TEXT': sql.SQL('TEXT')}
    counts = {}
    with target.transaction():
        target.execute("SELECT pg_advisory_xact_lock(hashtextextended('question-fixture-import',0))")
        for table in TABLES:
            if target.execute('SELECT to_regclass(%s)', (table,)).fetchone()[0] is not None:
                raise ValueError('Target table already exists: ' + table)
        for table in TABLES:
            info = source.execute('PRAGMA table_info(' + table + ')').fetchall()
            if not info:
                raise ValueError('Source table missing: ' + table)
            primary = [r[1] for r in sorted(info, key=lambda r: r[5]) if r[5]]
            definitions = []
            for _, name, kind, required, _, pk in info:
                if kind not in types:
                    raise ValueError('Unsupported source type: ' + table)
                identity = sql.SQL(' GENERATED BY DEFAULT AS IDENTITY') if name == 'id' and pk and kind == 'INTEGER' else sql.SQL('')
                required_sql = sql.SQL(' NOT NULL') if required or pk else sql.SQL('')
                definitions.append(sql.SQL('{} {}{}{}').format(sql.Identifier(name), types[kind], identity, required_sql))
            if primary:
                definitions.append(sql.SQL('PRIMARY KEY ({})').format(sql.SQL(',').join(map(sql.Identifier, primary))))
            target.execute(sql.SQL('CREATE TABLE {} ({})').format(sql.Identifier(table), sql.SQL(',').join(definitions)))
            columns = [r[1] for r in info]
            insert = sql.SQL('INSERT INTO {} ({}) VALUES ({})').format(sql.Identifier(table),
                sql.SQL(',').join(map(sql.Identifier, columns)), sql.SQL(',').join([sql.Placeholder()] * len(columns)))
            rows = source.execute('SELECT * FROM ' + table)
            count = 0
            with target.cursor() as cur:
                while batch := rows.fetchmany(500):
                    cur.executemany(insert, batch)
                    count += len(batch)
            if target.execute(sql.SQL('SELECT count(*) FROM {}').format(sql.Identifier(table))).fetchone()[0] != count:
                raise ValueError('Row count mismatch: ' + table)
            counts[table] = count
            if any(r[1] == 'id' and r[5] and r[2] == 'INTEGER' for r in info):
                has_seq = source.execute("SELECT 1 FROM sqlite_master WHERE name='sqlite_sequence'").fetchone()
                prior = source.execute('SELECT seq FROM sqlite_sequence WHERE name=?', (table,)).fetchone() if has_seq else None
                high = int(prior[0]) if prior else 0
                maximum = target.execute(sql.SQL('SELECT COALESCE(max(id),0) FROM {}').format(sql.Identifier(table))).fetchone()[0]
                high = max(high, maximum)
                target.execute("SELECT setval(pg_get_serial_sequence(%s,'id'),%s,%s)", (table, max(high, 1), high > 0))
    return counts

"""Value-chain report generation (pipeline.chain_report) with its own records on the candidate PG schema.

The unchanged legacy build reads its material (value-chain map, expectations, transcripts, feed) from the projection
and calls the models as before. Only what it writes goes here: the report row, updated stage by stage while the
screen polls it, the per-node note cache, and its run record. These are written outside any request, so they cannot
wait for a projection build; the report and history reads look here first, then at the collected (projection) rows.
Candidate report ids start at ID_START so they never meet an id the legacy writer used.
"""
import logging

from pipeline.postgres_graph_fixture import _guard

log = logging.getLogger(__name__)
ID_START = 1_000_000
COLUMNS = ('id', 'root', 'status', 'progress', 'tree_json', 'body', 'refs_json', 'missing_json', 'inputs_hash', 'model',
           'error', 'created_at', 'finished_at', 'analysis', 'outline')
UPDATABLE = set(COLUMNS) - {'id', 'root', 'created_at'}
NOW = "to_char(timezone('utc',now()),'YYYY-MM-DD HH24:MI:SS')"


def initialize(conn):
    _guard(conn)
    with conn.transaction():
        conn.execute(f'CREATE TABLE IF NOT EXISTS candidate_chain_reports (id BIGINT GENERATED BY DEFAULT AS IDENTITY '
                     f'(START WITH {ID_START}) PRIMARY KEY,root TEXT NOT NULL,status TEXT NOT NULL,progress TEXT,tree_json TEXT,'
                     'body TEXT,refs_json TEXT,missing_json TEXT,inputs_hash TEXT,model TEXT,error TEXT,'
                     f'created_at TEXT NOT NULL DEFAULT {NOW},finished_at TEXT,analysis TEXT,outline TEXT)')
        conn.execute('CREATE INDEX IF NOT EXISTS candidate_chain_reports_root ON candidate_chain_reports(root,id)')
        conn.execute('CREATE TABLE IF NOT EXISTS candidate_chain_node_notes (node_key TEXT NOT NULL,inputs_hash TEXT NOT NULL,'
                     f'body TEXT NOT NULL,model TEXT,created_at TEXT NOT NULL DEFAULT {NOW},PRIMARY KEY (node_key,inputs_hash))')


def install(chain_report, connect):
    """Point the legacy module's writes and record reads at PG (`connect` opens a new connection per use)."""
    collected_read, collected_history, collected_note = chain_report.read, chain_report.history, chain_report._cached_note

    def start(root, outline='bottom_up'):
        with connect() as pg:
            row = pg.execute("SELECT id FROM candidate_chain_reports WHERE root=%s AND COALESCE(outline,'bottom_up')=%s "
                             f"AND status='running' AND created_at >= to_char(timezone('utc',now()) - interval '30 minutes',"
                             "'YYYY-MM-DD HH24:MI:SS') ORDER BY id DESC LIMIT 1", (root, outline)).fetchone()
            if row:
                return row[0], False
            rid = pg.execute("INSERT INTO candidate_chain_reports (root,status,progress,model,outline) VALUES "
                             "(%s,'running','트리 고르는 중',%s,%s) RETURNING id",
                             (root, f'{chain_report.NOTE_MODEL}+{chain_report.SYNTH_MODEL}+{chain_report.WRITER_MODEL}',
                              outline)).fetchone()[0]
            return rid, True

    def update(rid, **cols):
        if not set(cols) <= UPDATABLE:
            raise ValueError(f'Unknown report columns: {sorted(set(cols) - UPDATABLE)}')
        with connect() as pg:
            pg.execute(f"UPDATE candidate_chain_reports SET {', '.join(f'{k}=%s' for k in cols)} WHERE id=%s",
                       (*cols.values(), rid))

    def read(rid):
        if rid < ID_START:
            return collected_read(rid)
        with connect() as pg:
            cur = pg.execute(f'SELECT {",".join(COLUMNS)} FROM candidate_chain_reports WHERE id=%s', (rid,))
            row = cur.fetchone()
        if row is None:
            return None
        import json
        r = dict(zip(COLUMNS, row))
        j = lambda v: json.loads(v) if v else []  # noqa: E731 - same decoding as the legacy read
        return {**{k: r[k] for k in ('id', 'root', 'status', 'progress', 'body', 'analysis', 'model', 'error', 'created_at',
                                     'finished_at')},
                'outline': r['outline'] or 'bottom_up',
                'tree': j(r['tree_json']), 'refs': j(r['refs_json']), 'missing': j(r['missing_json'])}

    def history(root, limit=10):
        with connect() as pg:
            own = [dict(zip(('id', 'root', 'status', 'outline', 'created_at', 'finished_at'), row)) for row in pg.execute(
                "SELECT id,root,status,COALESCE(outline,'bottom_up'),created_at,finished_at FROM candidate_chain_reports "
                'WHERE root=%s ORDER BY id DESC LIMIT %s', (root, limit))]
        return sorted(own + collected_history(root, limit), key=lambda r: r['id'], reverse=True)[:limit]

    def cached_note(key, h):
        with connect() as pg:
            row = pg.execute('SELECT body FROM candidate_chain_node_notes WHERE node_key=%s AND inputs_hash=%s',
                             (key, h)).fetchone()
        return row[0] if row else collected_note(key, h)

    def store_note(key, h, body):
        with connect() as pg:
            pg.execute('INSERT INTO candidate_chain_node_notes (node_key,inputs_hash,body,model) VALUES (%s,%s,%s,%s) '
                       'ON CONFLICT (node_key,inputs_hash) DO UPDATE SET body=excluded.body,model=excluded.model,'
                       f'created_at={NOW}', (key, h, body, chain_report.NOTE_MODEL))

    def record(status, summary):
        from pipeline.ops import mask_secrets
        with connect() as pg:
            if pg.execute("SELECT to_regclass('candidate_job_runs')").fetchone()[0] is None:
                log.warning('chain_report run not recorded: candidate_job_runs missing')
                return
            pg.execute(f'INSERT INTO candidate_job_runs (job,status,summary,ran_at) VALUES (%s,%s,%s,{NOW})',
                       ('chain_report', status, mask_secrets(summary or '')[:500]))

    chain_report.start, chain_report._update, chain_report.read, chain_report.history = start, update, read, history
    chain_report._cached_note, chain_report._store_note, chain_report._record = cached_note, store_note, record


def ready(conn):
    return conn.execute("SELECT to_regclass('candidate_chain_reports')").fetchone()[0] is not None

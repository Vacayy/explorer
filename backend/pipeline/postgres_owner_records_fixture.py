"""Owner-scoped follows and prediction pins for the disposable single-path candidate.

The legacy tables had no owner column. Rows move, with their IDs and times, to
the account explicitly mapped to the archived owner portfolio; nothing is
inferred. Legacy reads see these ledgers through the projection.
"""
from pipeline.postgres_graph_fixture import _guard


def owner_account(conn):
    rows = conn.execute('SELECT account_id FROM fixture_portfolio_legacy_mapping').fetchall()
    if len(rows) != 1:
        raise LookupError('Exactly one explicitly mapped owner is required')
    return rows[0][0]


def initialize_owner_records(conn):
    _guard(conn)
    with conn.transaction():
        if conn.execute("SELECT to_regclass('owner_follows')").fetchone()[0] is not None:
            raise ValueError('Owner records already initialized')
        account = owner_account(conn)
        conn.execute('CREATE TABLE owner_follows (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,'
                     'account_id BIGINT NOT NULL REFERENCES fixture_portfolio_accounts(id),entity_id BIGINT NOT NULL,'
                     "created_at TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'),"
                     'UNIQUE(account_id,entity_id))')
        conn.execute('CREATE TABLE owner_kalshi_pins (account_id BIGINT NOT NULL REFERENCES fixture_portfolio_accounts(id),'
                     'event_ticker TEXT NOT NULL,series_ticker TEXT NOT NULL,'
                     "pinned_at TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'),"
                     'PRIMARY KEY(account_id,event_ticker))')
        follows = [row for (row,) in conn.execute("SELECT row_data FROM legacy_snapshot_rows WHERE table_name='follows' "
                                                  "ORDER BY (row_data->>'id')::bigint")]
        for row in follows:
            conn.execute('INSERT INTO owner_follows(id,account_id,entity_id,created_at) VALUES (%s,%s,%s,%s)',
                         (row['id'], account, row['entity_id'], row['created_at']))
        conn.execute("SELECT setval(pg_get_serial_sequence('owner_follows','id'),"
                     "GREATEST((SELECT coalesce(max(id),0) FROM owner_follows),1),TRUE)")
        pins = [row for (row,) in conn.execute("SELECT row_data FROM legacy_snapshot_rows WHERE table_name='kalshi_pins'")]
        for row in pins:
            conn.execute('INSERT INTO owner_kalshi_pins VALUES (%s,%s,%s,%s)',
                         (account, row['event_ticker'], row['series_ticker'], row['pinned_at']))
        return {'follows': len(follows), 'pins': len(pins)}


def entity(conn, *, ident=None, kind=None, name=None):
    if ident is not None:
        rows = conn.execute("SELECT row_data FROM legacy_snapshot_rows WHERE table_name='entities' AND row_data->>'id'=%s",
                            (str(ident),)).fetchall()
    else:
        # Same row the legacy `WHERE type=? AND name=?` lookup returns first.
        rows = conn.execute("SELECT row_data FROM legacy_snapshot_rows WHERE table_name='entities' AND row_data->>'type'=%s "
                            "AND row_data->>'name'=%s ORDER BY (row_data->>'id')::bigint LIMIT 1", (kind, name)).fetchall()
    return rows[0][0] if rows else None


def follows(conn):
    account = owner_account(conn)
    ids = [row[0] for row in conn.execute('SELECT entity_id FROM owner_follows WHERE account_id=%s ORDER BY created_at,id', (account,))]
    found = {int(row['id']): row for (row,) in conn.execute(
        "SELECT row_data FROM legacy_snapshot_rows WHERE table_name='entities' AND row_data->>'id'=ANY(%s)",
        ([str(i) for i in ids],))}
    return [{'entity_id': i, 'type': found[i]['type'], 'name': found[i]['name']} for i in ids if i in found]


def follow(conn, entity_id):
    conn.execute('INSERT INTO owner_follows(account_id,entity_id) VALUES (%s,%s) ON CONFLICT DO NOTHING',
                 (owner_account(conn), entity_id))


def unfollow(conn, entity_id):
    conn.execute('DELETE FROM owner_follows WHERE account_id=%s AND entity_id=%s', (owner_account(conn), entity_id))


def set_pin(conn, event_ticker, series_ticker, on):
    account = owner_account(conn)
    if on:
        conn.execute('INSERT INTO owner_kalshi_pins(account_id,event_ticker,series_ticker) VALUES (%s,%s,%s) ON CONFLICT DO NOTHING',
                     (account, event_ticker, series_ticker))
    else:
        conn.execute('DELETE FROM owner_kalshi_pins WHERE account_id=%s AND event_ticker=%s', (account, event_ticker))
    return on

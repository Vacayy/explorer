"""Existing video enrichment against the disposable single-path graph."""
from collections import Counter
import math

from psycopg.types.json import Jsonb
from pipeline.postgres_graph_fixture import _guard
from services.tagging_service import INDUSTRY_KEYWORDS, TOPIC_KEYWORDS


def initialize_video_model_calls(target):
    _guard(target)
    if target.execute("SELECT to_regclass('video_model_calls')").fetchone()[0] is not None:
        raise ValueError('Video model call ledger already exists')
    target.execute("CREATE TABLE video_model_calls (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
        "document_id BIGINT NOT NULL,task TEXT NOT NULL,model TEXT,engine TEXT,effort TEXT, "
        "duration_ms BIGINT,ok BOOLEAN NOT NULL,usage JSONB NOT NULL,cost_usd DOUBLE PRECISION, "
        "created_at TIMESTAMPTZ NOT NULL DEFAULT now())")


def video_call_recorder(factory, doc_id):
    """Record usage metadata without prompts, outputs, or exception text."""
    def record(task, model, engine, effort, result, duration_ms, error):
        usage = (result.usage or {}) if result is not None else {}
        safe = {k: v for k, v in usage.items() if k in {'input', 'output', 'cache_create', 'cache_read', 'thinking'}
                and isinstance(v, int) and not isinstance(v, bool) and v >= 0}
        cost = result.cost_usd if result is not None else None
        if not isinstance(cost, (int, float)) or isinstance(cost, bool) or not math.isfinite(cost) or cost < 0:
            cost = None
        with factory() as pg:
            _guard(pg)
            pg.execute('INSERT INTO video_model_calls(document_id,task,model,engine,effort,duration_ms,ok,usage,cost_usd) '
                       'VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s)',
                       (doc_id, task, model, engine, effort, duration_ms, error is None, Jsonb(safe), cost))
    return record


def video_vocabulary(factory):
    """Build the existing enrichment vocabulary from the same PG graph."""
    with factory() as pg:
        pg.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY')
        _guard(pg)
        metadata = {r[0] for r in pg.execute("SELECT table_name FROM legacy_snapshot_tables WHERE table_name IN ('entities','entity_links')")}
        if metadata != {'entities', 'entity_links'}:
            raise ValueError('Graph vocabulary sources are incomplete')
        entities = [r[0] for r in pg.execute("SELECT row_data FROM legacy_snapshot_rows WHERE table_name='entities' ORDER BY row_ordinal")]
        counts = Counter((r[0].get('entity_id'), r[0].get('link_type')) for r in
                         pg.execute("SELECT row_data FROM legacy_snapshot_rows WHERE table_name='entity_links'"))
    totals = Counter()
    for (ident, _), count in counts.items():
        totals[ident] += count
    def ranked(kind, link_type=None, *, unlinked=False):
        candidates = []
        for entity in entities:
            if entity.get('type') != kind:
                continue
            if kind == 'company' and (entity.get('aliases') is not None or entity.get('status') == 'merged'):
                continue
            ident = entity['id']
            count = counts.get((ident, link_type), 0) if link_type else totals[ident]
            if unlinked or count:
                candidates.append((count, ident, entity.get('name') or ''))
        return [name for _, _, name in sorted(candidates, key=lambda row: (-row[0], row[1]))[:40] if name]
    industries = list(dict.fromkeys([*ranked('sector', 'industry'), *INDUSTRY_KEYWORDS]))
    topics = list(dict.fromkeys([*ranked('theme', 'topic'), *TOPIC_KEYWORDS]))
    return industries, topics, ranked('person', 'person'), ranked('company', unlinked=True)


def video_analyzer(factory, doc_id):
    from pipeline.enrich import enrich
    recorder = video_call_recorder(factory, doc_id)
    return lambda title, body: enrich(title, body, vocabulary_provider=lambda: video_vocabulary(factory), record_call=recorder)

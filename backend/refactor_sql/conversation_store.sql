-- Applied only to an explicitly selected isolated schema by the caller.
-- SQLite IDs and original JSON text are retained for a later checked import.
CREATE TABLE conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT,
    anchor_entity_id BIGINT,
    channel TEXT NOT NULL DEFAULT 'web',
    chat_id TEXT,
    summary TEXT,
    state_json TEXT,
    created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    role TEXT NOT NULL,
    content TEXT NOT NULL,
    citations_json TEXT,
    gaps_json TEXT,
    model TEXT,
    route_json TEXT,
    attachments_json TEXT,
    created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX chat_messages_conversation_order ON chat_messages (conversation_id, id);

-- Entity IDs refer to the imported source snapshot; cross-snapshot validity
-- must be checked by the importer before any live cutover.
CREATE TABLE chat_entity_links (
    message_id BIGINT NOT NULL REFERENCES chat_messages(id) ON DELETE CASCADE,
    entity_id BIGINT NOT NULL,
    link_type TEXT,
    UNIQUE (message_id, entity_id)
);

-- Preserve citations that were already dangling in the source snapshot.
-- An importer must never manufacture a document or silently drop its ID.
CREATE TABLE conversation_import_unresolved_docs (
    document_id BIGINT PRIMARY KEY,
    reason TEXT NOT NULL CHECK (reason = 'missing_in_source')
);

-- Distinguish imported conversations from new PG conversations when an old
-- dangling document ID is later reused in the new document store.
CREATE TABLE conversation_import_origin (
    conversation_id BIGINT PRIMARY KEY REFERENCES conversations(id) ON DELETE CASCADE
);

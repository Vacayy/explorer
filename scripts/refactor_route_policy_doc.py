"""Regenerate docs/specs/candidate-route-policy-draft.md from routes.json and the enforced route_policy.

  python3 scripts/refactor_route_policy_doc.py
Reads only the policy block of the boundary module, so it runs without the backend's dependencies.
"""
import collections, json, os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = open(os.path.join(ROOT, 'backend/routers/postgres_access_boundary.py')).read()
ns = {'re': re}
exec(src[src.index('POLICIES ='):src.index('def route_policies')], ns)
routes = json.load(open(os.path.join(ROOT, 'frontend/src/api/generated/routes.json')))
rows = sorted({(r['method'].upper(), r['path']) for r in routes})
policy = {key: ns['route_policy'](*key) for key in rows}
count = collections.Counter(policy.values())
order = ['member', 'operator', 'compute', 'public', 'auth']
out = ['# Candidate route policy (generated by scripts/refactor_route_policy_doc.py from frontend routes.json and '
       '`routers/postgres_access_boundary.route_policy`)', '',
       'Enforced in the public mode by `CandidateAccessBoundary`; the private (loopback) mode has no boundary.',
       '`public` = collected-data reads, open to everyone (personal parts come from the requester-scoped read shadow: '
       'an anonymous visitor sees none, a member their own).',
       "`member` = signed-in member or operator; personal ledgers are the requester's own (portfolio, saved, follows, "
       'prediction pins, read marks, tracker conditions, watch groups, studies, conversations, tracked questions).',
       '`compute` = open writes whose cost is limited where a model is actually called (usage gate; anonymous requests '
       'also rate-limited per network).',
       '`operator` = admin, collection settings and triggers, operator-only computations, and personal settings not per '
       'member yet (transcript follow/core pin, trade follow, group evaluation and watch reasons, tracker flow preparation).',
       '', '| policy | count |', '|---|---|']
out += [f'| {p} | {count[p]} |' for p in order if count[p]]
out += ['', '| method | path | policy |', '|---|---|---|']
out += [f'| {m} | `{p}` | {policy[(m, p)]} |' for m, p in sorted(rows, key=lambda k: (order.index(policy[k]), k[1], k[0]))]
open(os.path.join(ROOT, 'docs/specs/candidate-route-policy-draft.md'), 'w').write('\n'.join(out) + '\n')
print(dict(count), len(rows))
